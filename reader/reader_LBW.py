EXPECTED_FIELDS = 9

def _split_path(path):
    """Split both Windows and POSIX separators consistently."""
    return path.replace("\\", "/").split("/")


def _subject_from_image_path(path):
    parts = _split_path(path)
    if len(parts) < 2:
        return ""
    return parts[1].split("_")[0]


def _parse_pair(text, name):
    values = text.split(",")
    if len(values) != 2:
        raise ValueError(f"Invalid {name} field: {text!r}")
    try:
        return [float(values[0]), float(values[1])]
    except ValueError as exc:
        raise ValueError(f"Invalid numeric {name} field: {text!r}") from exc

def _parse_triplet(text, name):
    values = text.split(",")
    if len(values) != 3:
        raise ValueError(f"Invalid {name} field: {text!r}")
    try:
        return [float(values[0]), float(values[1]), float(values[2])]
    except ValueError as exc:
        raise ValueError(f"Invalid numeric {name} field: {text!r}") from exc

def Decode_LBW(line):
    anno = edict()
    parts = line.strip().split()

    if not parts:
        raise ValueError("Empty LBW label line")

    if len(parts) < EXPECTED_FIELDS:
        raise ValueError(
            "Invalid LBW label format: "
            f"expected >= {EXPECTED_FIELDS} fields, got {len(parts)}\n"
            f"Line: {line.strip()}"
        )

    anno.face = parts[0]    #facesave
    anno.gaze2d = _parse_pair(parts[1], "gaze2d")
    anno.gaze3d = _parse_triplet(parts[2], "gaze3d")
    anno.fgaze3d = _parse_triplet(parts[3], "fgaze3d")
    anno.gaze = _parse_pair(parts[4], "GazeYawPitch")     #fgaze2d
    anno.left2d = _parse_pair(parts[5], "left2d")
    anno.pface = parts[6]
    anno.pgaze = _parse_triplet(parts[7], "pgaze")
    anno.pgaze2d = _parse_pair(parts[8], "pgaze2d")

    return anno



